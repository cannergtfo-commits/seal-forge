export function printedOf(card: Pick<CardDef, "edition" | "tokenId">): Printed | null {
  return PRINTED[`${card.edition}:${card.tokenId}`] ?? null;
}

export type PrintedField = "name" | "text" | "cost" | "atk" | "hp";

/** Fields where the NFT metadata differs from the current game card. Empty when they match. */
export function printedDiff(card: CardDef): { field: PrintedField; printed: string | number; current: string | number }[] {
  const printed = printedOf(card);
  if (!printed) return [];
  const out: { field: PrintedField; printed: string | number; current: string | number }[] = [];
  if (printed.name !== card.name) out.push({ field: "name", printed: printed.name, current: card.name });
  if (printed.text !== card.text) out.push({ field: "text", printed: printed.text, current: card.text });
  for (const field of ["cost", "atk", "hp"] as const) {
    const value = printed[field];
    if (value !== undefined && value !== card[field]) out.push({ field, printed: value, current: card[field] });
  }
  return out;
}

/** True when a stat or name changed, not just wording. UI can show a "Rebalanced" badge. */
export function isRebalanced(card: CardDef): boolean {
  return printedDiff(card).some((item) => item.field !== "text");
}
